CREATE TABLE PUBLISHERS (
	id   UUID,
	name VARCHAR(128) NOT NULL,

	CONSTRAINT PK_PUBLISHERS PRIMARY KEY(id)
);

CREATE TABLE GS1_CODES (
	code         VARCHAR(9),
	publisher_id UUID        NOT NULL,

	CONSTRAINT PK_GS1_CODES PRIMARY KEY(code),
	CONSTRAINT FK_GS1_CODES_PUBLISHERS FOREIGN KEY (publisher_id) REFERENCES PUBLISHERS (id)
);

CREATE TABLE PUBLISHINGS (
	id           UUID,
	publisher_id UUID,
	name         VARCHAR(128) NOT NULL,
	ean          VARCHAR(16),

	CONSTRAINT PK_PUBLISHINGS PRIMARY KEY(id),
	CONSTRAINT FK_PUBLISHINGS_PUBLISHERS FOREIGN KEY (publisher_id) REFERENCES PUBLISHERS (id)
);

CREATE TABLE BOOKS (
	id            UUID,
	publishing_id UUID,
	publisher_id  UUID,
	title         VARCHAR(128) NOT NULL,
	ean           VARCHAR(16),
	url           VARCHAR(256),
	variant       INTEGER      NOT NULL,

	CONSTRAINT PK_BOOKS PRIMARY KEY(id),
	CONSTRAINT FK_BOOKS_PUBLISHINGS FOREIGN KEY (publishing_id) REFERENCES PUBLISHINGS (id),
	CONSTRAINT FK_BOOKS_PUBLISHERS FOREIGN KEY (publisher_id) REFERENCES PUBLISHERS (id),

	-- A book can belong to a publishing or a publisher.
	CONSTRAINT CHK_BOOKS_PUBLISHING_XOR_PUBLISHER CHECK (
		(publishing_id IS NOT NULL AND publisher_id IS NULL)
		OR
		(publishing_id IS NULL AND publisher_id IS NOT NULL)
	)
);

CREATE TABLE COMIC_BOOKS (
	book_id      UUID,
	issue_number INTEGER,
	issue_date   DATE,

	CONSTRAINT PK_COMIC_BOOKS PRIMARY KEY(book_id),
	CONSTRAINT FK_COMIC_BOOKS_BOOKS FOREIGN KEY (book_id) REFERENCES BOOKS (id)
);

CREATE TABLE COMIC_BOOKS_CONTAINS (
	comic_book_id           UUID,
	comic_book_id_contained UUID,

	CONSTRAINT PK_COMIC_BOOKS_CONTAINS PRIMARY KEY(comic_book_id, comic_book_id_contained),
	CONSTRAINT FK_COMIC_BOOKS_CONTAINS_COMIC_BOOKS_1 FOREIGN KEY (comic_book_id) REFERENCES COMIC_BOOKS (book_id),
	CONSTRAINT FK_COMIC_BOOKS_CONTAINS_COMIC_BOOKS_2 FOREIGN KEY (comic_book_id_contained) REFERENCES COMIC_BOOKS (book_id)
);

CREATE TABLE SERIES (
	id   UUID,
	name VARCHAR(128) NOT NULL,

	CONSTRAINT PK_SERIES PRIMARY KEY(id)
);

CREATE TABLE BOOK_READING_ORDER (
	series_id UUID,
	book_id   UUID,
	ordering  INTEGER NOT NULL,

	CONSTRAINT PK_BOOK_READING_ORDER PRIMARY KEY (series_id, book_id),
	CONSTRAINT FK_BOOK_READING_ORDER_SERIES FOREIGN KEY (series_id) REFERENCES SERIES (id),
	CONSTRAINT FK_BOOK_READING_ORDER_BOOKS FOREIGN KEY (book_id) REFERENCES BOOKS (id)
);
